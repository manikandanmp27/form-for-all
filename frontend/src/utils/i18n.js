// Translation helper function
export const getTranslation = (lang, key) => {
  const dictionary = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.English;
  return dictionary[key] || UI_TRANSLATIONS.English[key] || key;
};

// Field translator helper
export const translateField = (field, lang) => {
  if (!field || !lang || lang === 'English') return field;

  const fieldKey = field.fieldName || field.id;
  const translatedMap = FIELD_TRANSLATIONS[fieldKey]?.[lang];

  if (translatedMap) {
    return {
      ...field,
      label: translatedMap.label || field.label,
      description: translatedMap.description || field.description,
      whyAsked: translatedMap.whyAsked || field.whyAsked,
      riskWarning: translatedMap.riskWarning || field.riskWarning,
    };
  }

  return field;
};
